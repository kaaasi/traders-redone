"""Extract the field order of the original save routine (2336:000A) from the disassembly.

Usage: python3 -I tools/datenlayout/savegame.py ~/traders-referenz/analyse/disasm/2336.asm > tests/Traders.Tests/State/SaveGameSites.txt

The save routine writes every value as a 32-bit dword via `call 2336:051E`. For each call
site this prints, in program order (loops not unrolled):

    <DS base offset hex> <width 1|2|4> <signed|unsigned> <indexed|scalar>

Width/sign come from the instructions loading the value:
  mov al,[..] + cbw            -> 1 signed      mov al,[..] + mov ah,0  -> 1 unsigned
  mov ax,[..] + cwd            -> 2 signed      push 0 / push word [..] -> 2 unsigned
  push word [x+2] / push word [x] -> 4
The C# description (Traders.Core.State.SaveGameLayout) is checked against this file in a test,
so the two independent readings of the routine must agree.
"""
import re, sys

lines = []
inside = False
for line in open(sys.argv[1]):
    if line.startswith('; ---- 2336:000A'):
        inside = True
        continue
    if inside and line.startswith('; ---- '):
        break
    m = re.match(r'([0-9A-F]{8})\s+[0-9A-F]+\s+(.*)$', line)
    if inside and m:
        lines.append(m.group(2).strip())

MEM = re.compile(r'\[(?:(?:bx|si|bx\+si)\+)?0x([0-9a-f]+)\]')
out = []
for i, ins in enumerate(lines):
    if ins != 'call 0x2336:0x51e':
        continue
    window = lines[max(0, i - 12):i]
    # dword: two consecutive word pushes of x+2 then x
    if window[-2].startswith('push word') and window[-1].startswith('push word'):
        hi = int(MEM.search(window[-2]).group(1), 16)
        lo = MEM.search(window[-1])
        assert hi == int(lo.group(1), 16) + 2, window
        idx = 'indexed' if '+' in window[-1] else 'scalar'
        out.append(f'{int(lo.group(1), 16):04X} 4 signed {idx}')
        continue
    if window[-1].startswith('push word'):
        # unsigned word: xor dx,dx / push dx / ... / push word [..]
        assert 'xor dx,dx' in window[-5:] and 'push dx' in window[-4:], window
        m = MEM.search(window[-1])
        idx = 'indexed' if '+' in window[-1] else 'scalar'
        out.append(f'{int(m.group(1), 16):04X} 2 unsigned {idx}')
        continue
    # value in ax, extended to dx:ax (cwd) and pushed
    assert window[-2:] == ['push dx', 'push ax'] and window[-3] == 'cwd', (i, window)
    j = len(window) - 4
    if window[j] in ('cbw', 'mov ah,0x0'):
        signed = 'signed' if window[j] == 'cbw' else 'unsigned'
        load = window[j - 1]
        assert load.startswith('mov al,'), load
        width = 1
    else:
        load = window[j]
        assert load.startswith('mov ax,'), load
        signed, width = 'signed', 2
    m = MEM.search(load)
    idx = 'indexed' if '+' in load else 'scalar'
    out.append(f'{int(m.group(1), 16):04X} {width} {signed} {idx}')

print('# generated by tools/datenlayout/savegame.py from 2336:000A - do not edit')
print('\n'.join(out))
